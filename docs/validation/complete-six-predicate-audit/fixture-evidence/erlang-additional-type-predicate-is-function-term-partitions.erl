check([{Label,Value,Expected}|Rest]) ->
    Expected = erlang:is_function(Value),
    Expected = apply(erlang,is_function,[Value]),
    Named = fun erlang:is_function/1,
    Expected = Named(Value),
    Expected = guarded(Value),
    Expected = case Value of CaseValue when is_function(CaseValue) -> true; _ -> false end,
    Expected = if is_function(Value) -> true; true -> false end,
    Expected = case Value of AlternativeValue when hd(invalid_guard) =:= never; is_function(AlternativeValue) -> true; _ -> false end,
    Expected = (false orelse erlang:is_function(Value)),
    Expected = (true andalso erlang:is_function(Value)),
    Accepted = case Expected of true -> [Label]; false -> [] end,
    Accepted = [Label || ComprehensionValue <- [Value], is_function(ComprehensionValue)],
    self() ! {probe,Label,Value},
    Expected = receive {probe,Label,ReceiveValue} when is_function(ReceiveValue) -> true; {probe,Label,_} -> false after 1000 -> error(receive_timeout) end,
