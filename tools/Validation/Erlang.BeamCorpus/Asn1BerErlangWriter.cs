using System.Globalization;
using System.Text;

internal static class Asn1BerErlangWriter
{
    internal static void Write(Asn1BerSchema schema, string directory, string? asn1Options = null)
    {
        var source = new StringBuilder();
        var header = new StringBuilder();
        string guard = "_" + schema.Name.ToUpperInvariant().Replace('-', '_') + "_HRL_";
        header.AppendLine("%% Generated by the Erlang ASN.1 compiler. Version: 5.5.2")
            .AppendLine("%% Purpose: Erlang record definitions for each named and unnamed")
            .AppendLine("%% SEQUENCE and SET, and macro definitions for each value")
            .AppendLine($"%% definition in module {schema.Name}.")
            .AppendLine()
            .AppendLine($"-ifndef({guard}).")
            .AppendLine($"-define({guard}, true).")
            .AppendLine();
        source.AppendLine("%% Generated by the Erlang ASN.1 BER compiler. Version: 5.5.2")
            .AppendLine($"%% Purpose: Encoding and decoding of the types in {schema.Name}.")
            .AppendLine()
            .AppendLine($"-module({Atom(schema.Name)}).")
            .AppendLine("-moduledoc false.");
        if (asn1Options is not null)
        {
            source.AppendLine("-compile(nowarn_unused_vars).")
                .AppendLine("-dialyzer(no_improper_lists).")
                .AppendLine("-dialyzer(no_match).")
                .AppendLine($"-include(\"{schema.Name}.hrl\").")
                .AppendLine("-asn1_info([{vsn,'5.5.2'},")
                .AppendLine($"            {{module,{Atom(schema.Name)}}},")
                .AppendLine($"            {{options,{asn1Options}}}]).")
                .AppendLine();
        }
        source.AppendLine("-export([encoding_rule/0,maps/0,bit_string_format/0,")
            .AppendLine("         legacy_erlang_types/0]).")
            .AppendLine("-export(['dialyzer-suppressions'/1]).");
        foreach (string prefix in new[] { "enc_", "dec_" })
        {
            WriteExports(source, schema.Types.Keys.Select(name => TermAtom(prefix + name) + "/2"));
        }
        WriteExports(source, schema.Values.Keys.Select(name => TermAtom(name) + "/0"));
        source.AppendLine("-export([info/0]).")
            .AppendLine()
            .AppendLine("-export([encode/2,decode/2]).");
        source.AppendLine(Asn1BerErlangRuntime.PublicApi);

        foreach (string prefix in new[] { "enc", "dec" })
        {
            string dispatch = prefix == "enc" ? "encode_disp" : "decode_disp";
            foreach (string name in schema.Types.Keys)
            {
                source.AppendLine($"{dispatch}({Atom(name)}, Data) -> {TermAtom(prefix + "_" + name)}(Data);");
            }
            source.AppendLine($"{dispatch}(Type, _Data) -> exit({{error,{{asn1,{{undefined_type,Type}}}}}}).");
            source.AppendLine();
        }
        source.AppendLine(asn1Options is null
            ? $"info() -> [{{module,{Atom(schema.Name)}}},{{options,[ber,legacy_erlang_types]}}]."
            : Asn1BerErlangRuntime.Info);
        int codecStart = source.Length;
        var records = new HashSet<string>(StringComparer.Ordinal);
        var codecTypes = schema.Types.ToList();
        for (int codecIndex = 0; codecIndex < codecTypes.Count; codecIndex++)
        {
            var (name, type) = codecTypes[codecIndex];
            CollectInlineTypes(name, type, codecTypes);
            WriteRecords(type, header, records);
            if (codecIndex < schema.Types.Count)
            {
                bool tagged = TryCollectionTag(type, schema.Types, out int defaultTag, out int defaultTagByte);
                string encodeTags = tagged ? $"[<<{Number(defaultTagByte)}>>]" : "[]";
                string decodeTags = tagged ? $"[{Number(defaultTag)}]" : "[]";
                source.AppendLine($"{TermAtom("enc_" + name)}(Val) ->")
                    .AppendLine($"    {TermAtom("enc_" + name)}(Val, {encodeTags}).")
                    .AppendLine()
                    .AppendLine($"{TermAtom("dec_" + name)}(Tlv) ->")
                    .AppendLine($"   {TermAtom("dec_" + name)}(Tlv, {decodeTags}).")
                    .AppendLine();
            }
            var resolved = ResolveTaggedType(type, schema.Types);
            var reference = type is { Kind: "tagged", Element: { } taggedType } ? taggedType : type;
            if (reference is { Kind: "ref", Name: { } aliasTarget } && resolved.Kind is "sequence" or "choice" or "collection")
            {
                source.AppendLine($"{TermAtom("enc_" + name)}(Val, TagIn) ->")
                    .AppendLine($"   {TermAtom("enc_" + aliasTarget)}(Val, TagIn).")
                    .AppendLine($"{TermAtom("dec_" + name)}(Tlv, TagIn) ->")
                    .AppendLine($"{Atom("dec_" + aliasTarget)}(Tlv, TagIn).")
                    .AppendLine();
                continue;
            }
            if (resolved.Kind == "sequence" && WriteSequence(source, name, resolved, schema))
            {
                continue;
            }
            if (resolved.Kind == "choice" && WriteChoice(source, name, resolved, schema))
            {
                continue;
            }
            if (resolved.Kind == "octets")
            {
                source.AppendLine($"{TermAtom("enc_" + name)}(Val, TagIn) ->")
                    .AppendLine("encode_restricted_string(Val, TagIn).")
                    .AppendLine($"{TermAtom("dec_" + name)}(Tlv, TagIn) ->")
                    .AppendLine("begin")
                    .AppendLine("binary_to_list(decode_restricted_string(Tlv, TagIn))")
                    .AppendLine("end")
                    .AppendLine(".")
                    .AppendLine();
            }
            else if (resolved.Kind is "integer" or "null" or "boolean")
            {
                source.AppendLine($"{TermAtom("enc_" + name)}(Val, TagIn) ->")
                    .AppendLine($"encode_{resolved.Kind}(Val, TagIn).")
                    .AppendLine($"{TermAtom("dec_" + name)}(Tlv, TagIn) ->");
                string decode = $"decode_{resolved.Kind}(Tlv, TagIn)";
                if (resolved.Range is { } range)
                {
                    decode = ConstrainInteger(decode, "Val1", range, schema.Values);
                }
                source.AppendLine(decode + ".");
                if (resolved.Range is not null || resolved.Kind == "null")
                {
                    source.AppendLine();
                }
            }
            else if (resolved is { Kind: "collection", Element: { } item })
            {
                string element = item is { Kind: "ref", Name: { } target } ? target : name + "_SEQOF";
                bool tagged = TryCollectionTag(item, schema.Types, out int tag, out int tagByte);
                bool octets = ResolveTaggedType(item, schema.Types).Kind == "octets";
                WriteCollection(source, name, element, tag, tagByte, octets, tagged, schema.Types.ContainsKey(name));
            }
            else
            {
                throw new NotSupportedException($"No specialized ASN.1 codec for {name} ({resolved.Kind}).");
            }
        }
        string orderedCodecs = Asn1BerCodecOrdering.Order(source.ToString(codecStart, source.Length - codecStart), schema.Types, codecTypes);
        source.Length = codecStart;
        source.Append(orderedCodecs);
        foreach (var (name, value) in schema.Values)
        {
            source.AppendLine($"{TermAtom(name)}() ->")
                .AppendLine($"{Number(value)}.");
        }
        source.AppendLine()
            .AppendLine()
            .AppendLine("%%%")
            .AppendLine("%%% Run-time functions.")
            .AppendLine("%%%")
            .AppendLine()
            .AppendLine("'dialyzer-suppressions'(Arg) ->")
            .AppendLine("    ok.");
        source.Append(Asn1BerErlangRuntime.Source);
        foreach (var (name, value) in schema.Values)
        {
            header.AppendLine($"-define({Atom(name)}, {Number(value)}).");
        }
        header.AppendLine($"-endif. %% {guard}");
        Directory.CreateDirectory(directory);
        File.WriteAllText(Path.Combine(directory, schema.Name + ".erl"), source.ToString().ReplaceLineEndings("\n"));
        File.WriteAllText(Path.Combine(directory, schema.Name + ".hrl"), header.ToString().ReplaceLineEndings("\n"));
    }

    private static void WriteExports(StringBuilder source, IEnumerable<string> signatures)
    {
        string entries = string.Join(",\n", signatures);
        if (entries.Length != 0)
        {
            source.AppendLine("-export([")
                .AppendLine(entries)
                .AppendLine("]).")
                .AppendLine();
        }
    }

    private static void CollectInlineTypes(string name, Asn1BerSchema.Type type, List<KeyValuePair<string, Asn1BerSchema.Type>> types)
    {
        while (type.Kind == "tagged")
        {
            type = type.Element!;
        }
        void Add(string childName, Asn1BerSchema.Type child)
        {
            while (child.Kind == "tagged")
            {
                child = child.Element!;
            }
            if (child.Kind is "sequence" or "choice" or "collection")
            {
                types.Add(new(childName, child));
            }
        }
        if (type.Fields is { } fields)
        {
            foreach (var field in fields)
            {
                Add(name + "_" + field.Name, field.Type);
            }
        }
        if (type is { Kind: "collection", Element: { } element })
        {
            Add(name + "_SEQOF", element);
        }
    }

    private static bool WriteChoice(StringBuilder source, string name, Asn1BerSchema.Type type, Asn1BerSchema schema)
    {
        var alternatives = new List<(string Name, int Tag, string Encode, string Decode)>();
        foreach (var field in type.Fields!)
        {
            if (!TryCollectionTag(field.Type, schema.Types, out int tag, out int tagByte))
            {
                return false;
            }
            var resolved = ResolveTaggedType(field.Type, schema.Types);
            var reference = field.Type;
            while (reference.Kind == "tagged")
            {
                reference = reference.Element!;
            }
            string target = reference is { Kind: "ref", Name: { } alias } ? alias : name + "_" + field.Name;
            string encode = resolved.Kind switch
            {
                "octets" => "encode_restricted_string",
                "integer" or "null" or "boolean" => "encode_" + resolved.Kind,
                _ => Atom("enc_" + target)
            };
            string decode = resolved.Kind switch
            {
                "octets" => "begin\nbinary_to_list(decode_restricted_string(V1, []))\nend\n",
                "integer" or "null" or "boolean" => "decode_" + resolved.Kind + "(V1, [])",
                _ => Atom("dec_" + target) + "(V1, [])"
            };
            if (resolved.Range is { } range)
            {
                decode = ConstrainInteger(decode, "Val1", range, schema.Values);
            }
            alternatives.Add((field.Name, tag, $"{encode}(element(2,Val), [<<{Number(tagByte)}>>])", decode));
        }
        bool root = schema.Types.ContainsKey(name);
        string indentation = root ? "   " : "      ";
        string decoder = root ? TermAtom("dec_" + name) : Atom("dec_" + name);
        source.AppendLine($"{TermAtom("enc_" + name)}(Val, TagIn) ->")
            .AppendLine(indentation + "{EncBytes,EncLen} = case element(1,Val) of");
        foreach (var alternative in alternatives)
        {
            source.AppendLine($"      {TermAtom(alternative.Name)} ->")
                .AppendLine($"         {alternative.Encode};");
        }
        source.AppendLine("      Else ->")
            .AppendLine("         exit({error,{asn1,{invalid_choice_type,Else}}})")
            .AppendLine("   end,")
            .AppendLine()
            .AppendLine("encode_tags(TagIn, EncBytes, EncLen).")
            .AppendLine()
            .AppendLine()
            .AppendLine($"{decoder}(Tlv, TagIn) ->")
            .AppendLine("Tlv1 = match_tags(Tlv, TagIn),")
            .AppendLine("case (case Tlv1 of [CtempTlv1] -> CtempTlv1; _ -> Tlv1 end) of")
            .AppendLine();
        for (int index = 0; index < alternatives.Count; index++)
        {
            var alternative = alternatives[index];
            source.AppendLine($"%% {Atom(alternative.Name)}")
                .AppendLine($"    {{{Number(alternative.Tag)}, V1}} ->")
                .AppendLine($"        {{{TermAtom(alternative.Name)}, {alternative.Decode}}};")
                .AppendLine();
            if (index + 1 < alternatives.Count)
            {
                source.AppendLine();
            }
        }
        source.AppendLine("      Else ->")
            .AppendLine(type.Extensible
                ? "         {asn1_ExtAlt,ber_encode(Else)}"
                : "         exit({error,{asn1,{invalid_choice_tag,Else}}})")
            .AppendLine("   end")
            .AppendLine(".");
        return true;
    }

    private static bool WriteSequence(StringBuilder source, string name, Asn1BerSchema.Type type, Asn1BerSchema schema)
    {
        if (type.Fields is not { Count: > 0 })
        {
            return false;
        }
        var codecs = new List<(string Encode, string Decode, int Tag, string Presence)>();
        int enumerationIndex = 0;
        int constrainedIntegerIndex = 0;
        foreach (var field in type.Fields!)
        {
            bool tagged = TryCollectionTag(field.Type, schema.Types, out int tag, out int tagByte);
            if (!tagged && ResolveTaggedType(field.Type, schema.Types).Kind != "choice")
            {
                return false;
            }
            var resolved = ResolveTaggedType(field.Type, schema.Types);
            string encode;
            string decode;
            switch (resolved.Kind)
            {
                case "octets":
                    encode = $"encode_restricted_string(Cindex{{0}}, [<<{Number(tagByte)}>>])";
                    decode = $"begin\nbinary_to_list(decode_restricted_string(V{{0}}, [{Number(tag)}]))\nend\n";
                    break;
                case "enumerated":
                    string defaultName = "Default" + Number(++enumerationIndex);
                    encode = "case Cindex{0} of\n" + string.Join(";\n", resolved.Numbers!.Select(entry =>
                    {
                        var bytes = new List<int> { entry.Value & 255 };
                        int remaining = entry.Value >> 8;
                        while (!((remaining == 0 && bytes[0] < 128) || (remaining == -1 && bytes[0] >= 128)))
                        {
                            bytes.Insert(0, remaining & 255);
                            remaining >>= 8;
                        }
                        return $"{TermAtom(entry.Key)} -> encode_tags([<<{Number(tagByte)}>>], [{string.Join(",", bytes.Select(Number))}], {Number(bytes.Count)})";
                    })) + ";\nEnumval{0} -> exit({error,{asn1, {enumerated_not_in_range,Enumval{0}}}})\nend";
                    decode = $"case decode_integer(V{{0}}, [{Number(tag)}]) of\n"
                        + string.Join(";\n", resolved.Numbers!.Select(entry => $"{Number(entry.Value)} -> {TermAtom(entry.Key)}"))
                        + $";\n{defaultName} -> {{asn1_enum,{defaultName}}}\nend";
                    break;
                case "integer":
                case "null":
                case "boolean":
                    encode = $"encode_{resolved.Kind}(Cindex{{0}}, [<<{Number(tagByte)}>>])";
                    decode = $"decode_{resolved.Kind}(V{{0}}, [{Number(tag)}])";
                    if (resolved.Range is { } range)
                    {
                        decode = ConstrainInteger(decode, "Val" + Number(++constrainedIntegerIndex), range, schema.Values);
                    }
                    break;
                default:
                    var reference = field.Type;
                    while (reference.Kind == "tagged")
                    {
                        reference = reference.Element!;
                    }
                    string target = reference is { Kind: "ref", Name: { } alias } ? alias : name + "_" + field.Name;
                    string encodeTags = tagged ? $"[<<{Number(tagByte)}>>]" : "[]";
                    string decodeTags = tagged ? $"[{Number(tag)}]" : "[]";
                    encode = $"{Atom("enc_" + target)}(Cindex{{0}}, {encodeTags})";
                    decode = $"{Atom("dec_" + target)}(V{{0}}, {decodeTags})";
                    break;
            }
            codecs.Add((encode, decode, tag, field.Presence));
        }

        string Variables(string prefix) => string.Join(",", Enumerable.Range(1, codecs.Count).Select(index => prefix + Number(index)));
        bool root = schema.Types.ContainsKey(name);
        string decoder = root ? TermAtom("dec_" + name) : Atom("dec_" + name);
        string tupleIndentation = root ? "" : "   ";
        source.AppendLine($"{TermAtom("enc_" + name)}(Val, TagIn) ->")
            .AppendLine($"{tupleIndentation}{{_,{Variables("Cindex")}}} = Val,");
        for (int index = 1; index <= codecs.Count; index++)
        {
            var codec = codecs[index - 1];
            var field = type.Fields[index - 1];
            string encoded = codec.Encode.Replace("{0}", Number(index));
            if (codec.Presence == "optional")
            {
                encoded = $"case Cindex{index} of\n         asn1_NOVALUE -> {{<<>>,0}};\n         _ ->\n            {encoded}\n       end";
            }
            else if (codec.Presence == "default_false")
            {
                encoded = $"case Cindex{index} of\n         asn1_DEFAULT ->\n            {{<<>>,0}};\n"
                    + $"         _ when Cindex{index} =:= false ->\n            {{<<>>,0}};\n         _ ->\n            {encoded}\n       end";
            }
            WriteFieldSeparator(source, field.Name, index);
            string spacer = codec.Presence == "required" ? " " : "  ";
            source.AppendLine($"   {{EncBytes{index},EncLen{index}}} ={spacer}{encoded},");
        }
        string length = string.Join(" + ", Enumerable.Range(1, codecs.Count).Select(index => "EncLen" + Number(index)));
        source.AppendLine()
            .AppendLine($"   BytesSoFar = [{Variables("EncBytes").Replace(",", ", ")}],")
            .AppendLine($"LenSoFar = {length},")
            .AppendLine("encode_tags(TagIn, BytesSoFar, LenSoFar).")
            .AppendLine($"{decoder}(Tlv, TagIn) ->")
            .AppendLine("   %%-------------------------------------------------")
            .AppendLine("   %% decode tag and length")
            .AppendLine("   %%-------------------------------------------------")
            .AppendLine("Tlv1 = match_tags(Tlv, TagIn),");
        for (int index = 1; index <= codecs.Count; index++)
        {
            var codec = codecs[index - 1];
            WriteFieldSeparator(source, type.Fields[index - 1].Name, index);
            string decoded = codec.Decode.Replace("{0}", Number(index));
            if (codec.Presence == "required")
            {
                source.AppendLine($"[V{index}|Tlv{index + 1}] = Tlv{index},")
                    .AppendLine($"Term{index} = {decoded},");
            }
            else
            {
                string absent = codec.Presence == "optional" ? " asn1_NOVALUE, " : "false,";
                decoded = decoded.Replace($", [{Number(codec.Tag)}])", ", [])", StringComparison.Ordinal);
                source.AppendLine($"{{Term{index},Tlv{index + 1}}} = case Tlv{index} of")
                    .AppendLine($"[{{{Number(codec.Tag)},V{index}}}|TempTlv{index + 1}] ->")
                    .AppendLine($"    {{{decoded}, TempTlv{index + 1}}};")
                    .AppendLine("    _ ->")
                    .AppendLine($"        {{{absent}Tlv{index}}}")
                    .AppendLine("end,");
            }
        }
        source.AppendLine();
        if (!type.Extensible)
        {
            source.AppendLine($"[] = Tlv{codecs.Count + 1},");
        }
        else
        {
            source.AppendLine($"case Tlv{codecs.Count + 1} of [] -> true; _ -> true end,");
        }
        source.AppendLine($"Res1 = {{{Atom(type.Name!)},{Variables("Term")}}},")
            .AppendLine("Res1.");

        return true;
    }

    private static void WriteFieldSeparator(StringBuilder source, string name, int index)
    {
        source.AppendLine()
            .AppendLine("%%-------------------------------------------------")
            .AppendLine($"%% attribute {name}({index})")
            .AppendLine("%%-------------------------------------------------");
    }

    private static void WriteCollection(
        StringBuilder source, string name, string element, int tag, int tagByte, bool octets, bool tagged, bool root
    )
    {
        string encodeTags = tagged ? $"[<<{Number(tagByte)}>>]" : "[]";
        string decodeTags = tagged ? $"[{Number(tag)}]" : "[]";
        string encode = octets ? "encode_restricted_string" : Atom("enc_" + element);
        string decode = octets
            ? $"begin\nbinary_to_list(decode_restricted_string(V1, {decodeTags}))\nend\n"
            : $"{Atom("dec_" + element)}(V1, {decodeTags})";
        string components = Atom("enc_" + name + "_components");
        string decoder = root ? TermAtom("dec_" + name) : Atom("dec_" + name);
        string indentation = root ? "   " : "      ";
        source.AppendLine($"{TermAtom("enc_" + name)}(Val, TagIn) ->")
            .AppendLine($"{indentation}{{EncBytes,EncLen}} = {components}(Val,[],0),")
            .AppendLine("   encode_tags(TagIn, EncBytes, EncLen).")
            .AppendLine()
            .AppendLine($"{components}([], AccBytes, AccLen) ->")
            .AppendLine("   {lists:reverse(AccBytes),AccLen};")
            .AppendLine()
            .AppendLine($"{components}([H|T],AccBytes, AccLen) ->")
            .AppendLine($"   {{EncBytes,EncLen}} = {encode}(H, {encodeTags}),")
            .AppendLine($"   {components}(T,[EncBytes|AccBytes], AccLen + EncLen).")
            .AppendLine()
            .AppendLine($"{decoder}(Tlv, TagIn) ->")
            .AppendLine("   %%-------------------------------------------------")
            .AppendLine("   %% decode tag and length")
            .AppendLine("   %%-------------------------------------------------")
            .AppendLine("Tlv1 = match_tags(Tlv, TagIn),")
            .AppendLine($"[{decode} || V1 <- Tlv1].")
            .AppendLine()
            .AppendLine();
    }

    private static bool TryCollectionTag(
        Asn1BerSchema.Type type,
        IReadOnlyDictionary<string, Asn1BerSchema.Type> types,
        out int tag,
        out int tagByte
    )
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        while (type is { Kind: "ref", Name: { } alias } && seen.Add(alias) && types.TryGetValue(alias, out var target))
        {
            type = target;
        }
        if (type.Tag is not int wireTag || (wireTag & 65535) >= 31)
        {
            tag = tagByte = 0;

            return false;
        }

        var resolved = ResolveTaggedType(type, types);
        tag = wireTag;
        tagByte = ((tag >> 16) << 6) | (tag & 31);
        if (resolved.Kind is "sequence" or "collection" or "choice")
        {
            tagByte |= 32;
        }

        return true;
    }

    private static Asn1BerSchema.Type ResolveTaggedType(
        Asn1BerSchema.Type type,
        IReadOnlyDictionary<string, Asn1BerSchema.Type> types
    )
    {
        var seen = new HashSet<string>(StringComparer.Ordinal);
        while (true)
        {
            if (type is { Kind: "tagged", Element: { } element })
            {
                type = element;
            }
            else if (type is { Kind: "ref", Name: { } alias } && seen.Add(alias) && types.TryGetValue(alias, out var target))
            {
                type = target;
            }
            else
            {
                return type;
            }
        }
    }

    private static void WriteRecords(Asn1BerSchema.Type type, StringBuilder header, HashSet<string> records)
    {
        if (type.Kind == "sequence" && records.Add(type.Name!))
        {
            string fields = string.Join(",\n", type.Fields!.Select(field => "  " + TermAtom(field.Name) + (field.Presence switch
            {
                "optional" => " = asn1_NOVALUE",
                "default_false" => " = asn1_DEFAULT",
                _ => ""
            })));
            header.AppendLine($"-record({Atom(type.Name!)}, {{")
                .AppendLine(fields);
            if (type.Extensible)
            {
                header.AppendLine("  %% with extension mark");
            }
            header.AppendLine("}).").AppendLine();
        }
        if (type.Element is { } element)
        {
            WriteRecords(element, header, records);
        }
        if (type.Fields is { } members)
        {
            foreach (var field in members)
            {
                WriteRecords(field.Type, header, records);
            }
        }
    }

    private static string ConstrainInteger(string decode, string variable, (string Lower, string Upper) range,
        IReadOnlyDictionary<string, int> values) =>
        $"begin\n{variable} = {decode},\nif {Bound(range.Lower, values)} =< {variable}, {variable} =< {Bound(range.Upper, values)} ->\n{variable};\ntrue ->\nexit({{error,{{asn1,bad_range}}}})\nend\nend";

    private static string Bound(string bound, IReadOnlyDictionary<string, int> values)
    {
        if (int.TryParse(bound, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out int value)
            || values.TryGetValue(bound, out value))
        {
            return Number(value);
        }

        throw new InvalidOperationException($"Unknown ASN.1 integer bound {bound}.");
    }

    private static string TermAtom(string value) =>
        Erlang.Compiler.Lexer.Scan(value) is [{ Kind: "atom" }, _] ? value : Atom(value);

    private static string Atom(string value) => "'" + value + "'";
    private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);
}
