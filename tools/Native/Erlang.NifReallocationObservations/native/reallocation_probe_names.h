#ifndef ERLANG_NET_REALLOCATION_PROBE_NAMES_H
#define ERLANG_NET_REALLOCATION_PROBE_NAMES_H

/* Control IDs, payload extents and returned evidence bits are separate domains. */
enum ReallocationProbeCase {
    REALLOCATION_CASE_NULL_POSITIVE = 1,
    REALLOCATION_CASE_NULL_ZERO = 2,
    REALLOCATION_CASE_RESIZE_SEQUENCE = 3
};

enum ReallocationProbeSize {
    REALLOCATION_SIZE_INITIAL = 13,
    REALLOCATION_SIZE_GROWN = 37,
    REALLOCATION_SIZE_SHRUNK = 7,
    REALLOCATION_SIZE_ZERO = 0,
    REALLOCATION_SIZE_AFTER_ZERO = 5
};

enum ReallocationProbePattern {
    REALLOCATION_PATTERN_INITIAL = 49,
    REALLOCATION_PATTERN_GROWN = 87,
    REALLOCATION_PATTERN_AFTER_ZERO = 163
};

enum ReallocationProbeBit {
    REALLOCATION_BIT_INITIAL_NON_NULL = 1 << 0,
    REALLOCATION_BIT_INITIAL_PAYLOAD_VERIFIED = 1 << 1,
    REALLOCATION_BIT_GROW_NON_NULL = 1 << 2,
    REALLOCATION_BIT_GROW_PREFIX_VERIFIED = 1 << 3,
    REALLOCATION_BIT_SHRINK_NON_NULL = 1 << 4,
    REALLOCATION_BIT_SHRINK_PREFIX_VERIFIED = 1 << 5,
    REALLOCATION_BIT_ZERO_NON_NULL = 1 << 6,
    REALLOCATION_BIT_AFTER_ZERO_NON_NULL = 1 << 7,
    REALLOCATION_BIT_AFTER_ZERO_NEW_PAYLOAD_VERIFIED = 1 << 8,
    REALLOCATION_BIT_NO_PENDING_EXCEPTION = 1 << 9,
    REALLOCATION_BIT_CURRENT_POINTER_FREE_RETURNED = 1 << 10
};

enum ReallocationProbeProtocol {
    REALLOCATION_LOAD_MARKER = 42,
    REALLOCATION_LOAD_ACCEPT = 0,
    REALLOCATION_LOAD_VETO = 1,
    REALLOCATION_RESULT_NO_BITS = 0,
    REALLOCATION_PATTERN_BYTE_MODULUS = 256,
    REALLOCATION_INCREMENT_ARITY = 1,
    REALLOCATION_GREETING_ARITY = 0,
    REALLOCATION_FUNCTION_FLAGS = 0
};

#define REALLOCATION_INCREMENT_NAME "increment"
#define REALLOCATION_GREETING_NAME "greeting"
#define REALLOCATION_PROBE_GREETING "native realloc probe"

#endif
